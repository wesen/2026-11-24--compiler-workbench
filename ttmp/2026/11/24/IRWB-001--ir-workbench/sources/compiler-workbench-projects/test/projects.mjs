// projects.mjs: validate every built-in project and build its reference image.
//   front end on the concatenated sources · reference image (compiler/typed-rv32.js) · O-pipeline with
//   checks · image check · every workbench script on a fresh copy. node test/projects.mjs [id] [show]
import { writeFileSync } from "node:fs";
import { load, SITE } from "./load.mjs";
const ctx = load(["app/content/projects.js"]);
const { WB, typedRv32 } = ctx;
const mem = {}; const storage = { get: k => mem[k], set: (k, v) => (mem[k] = v) };
const concat = x => { const meta = JSON.parse(x.files["project.json"]); const typed = Object.keys(x.files).filter(f => f.endsWith(".typed")).sort(); const order = (meta.sources || []).concat(typed.filter(f => !(meta.sources || []).includes(f))); return order.map(f => x.files[f].endsWith("\n") ? x.files[f] : x.files[f] + "\n").join(""); };
const refs = {};
for (const x of ctx.WB_PROJECTS) {
  const source = concat(x);
  try {
    const r = typedRv32.compile(source, []);
    const starts = Object.entries(r.entries).sort((a, b) => a[1] - b[1]);
    const fns = {}; starts.forEach(([n, s], i) => fns[n] = { bytes: (i + 1 < starts.length ? starts[i + 1][1] : r.image.length) - s });
    refs[x.id] = { source: WB.hash(source), image: Buffer.from(r.image).toString("base64"), entries: r.entries, fns, bytes: r.image.length };
  } catch (e) { console.log("REF FAIL", x.id, e.message); }
}
writeFileSync(SITE + "app/content/references.js", "// references.js: images built from each project's sources by compiler/typed-rv32.js (default policy), for checks and comparisons. Generated by test/projects.mjs.\nglobalThis.WB_REFERENCES = " + JSON.stringify(refs) + ";\n");
const wb = WB.createWorkbench({ storage, projects: ctx.WB_PROJECTS, references: refs });
const only = process.argv[2] && process.argv[2] !== "all" ? process.argv[2] : null;
let failures = 0;
for (const x of ctx.WB_PROJECTS) {
  if (only && x.id !== only) continue;
  const row = { id: x.id };
  try {
    const pr = wb.projects.open(x.id), meta = pr.meta;
    let p = pr.program;
    if (p.status !== "ok") { console.log("FRONTEND", x.id, JSON.stringify(p.error)); failures++; continue; }
    row.files = pr.files.list().length;
    row.r0 = p.compile().bytes;
    const ref = p.check({ against: "reference", count: 40 });
    row.ref = ref.fns.map(f => `${f.agree}/${f.total}`).join(",");
    const pl = p.pipeline(meta.pipeline || "O2", { count: 30 });
    row.passes = pl.steps.filter(s => s.edits).map(s => s.pass).join(" ");
    const bad = pl.steps.filter(s => s.check && /(\d+)\/(\d+)/.test(s.check) && s.check.split(", ").some(c => { const [a, b] = c.split(" ")[1].split("/"); return a !== b; }));
    if (bad.length && meta.pipeline !== "broken") row.pipelineBad = bad.map(s => s.pass + " " + s.check).join("; ");
    const img = p.compile();
    row.bytes = img.bytes;
    const ic = img.check({ count: 40 });
    if (ic.status !== "agree" && meta.pipeline !== "broken") row.imageBad = JSON.stringify(ic.fns.find(f => f.status === "disagree"));
    p.checkout("r0");
    // every workbench script: on a fresh copy, so one cannot depend on another's leftovers
    row.scripts = {};
    for (const s of pr.scripts()) {
      const logs = [];
      try {
        const out = await pr.run(s.name, {}, { fresh: true, logs });
        row.scripts[s.name] = "ok";
        if (process.argv[3] === "show") { console.log(`--- ${x.id}/${s.name}\n` + logs.join("\n") + "\nRETURN\n" + WB.toYaml(out)); }
      } catch (e) { row.scripts[s.name] = "FAIL " + e.message.split("\n")[0]; failures++; }
    }
    row.ui = pr.uiScripts().map(u => u.name).join(" ");
  } catch (e) { row.error = e.message.split("\n").slice(0, 2).join(" "); failures++; }
  if (row.pipelineBad || row.imageBad) failures++;
  console.log(JSON.stringify(row));
}
console.log(failures ? `${failures} FAILURES` : "all projects ok");
