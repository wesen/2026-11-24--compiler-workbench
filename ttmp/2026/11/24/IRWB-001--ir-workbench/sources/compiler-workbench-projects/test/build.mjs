// build.mjs: generates app/content/reference.js and app/content/book.js from src/*.md, and
// app/sources.js, which embeds every file of the site so wb.source can read the running code.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
const ROOT = "/home/claude/wb2/", SITE = ROOT + "site/";
const header = what => `// ${what} Generated by test/build.mjs; edit the Markdown under src/ instead.\n`;

writeFileSync(SITE + "app/content/reference.js", header("reference.js: the API reference, shown in the Reference view, returned by wb.help(), and sent to the agent.") +
  "globalThis.WB_REFERENCE = " + JSON.stringify(readFileSync(ROOT + "src/reference.md", "utf8")) + ";\n");

// the built-in projects: every file under src/projects/<id>/, in the order index.json gives
const P = ROOT + "src/projects/";
const order = JSON.parse(readFileSync(P + "index.json", "utf8")).order;
const dirs = readdirSync(P).filter(d => statSync(P + d).isDirectory());
for (const d of dirs) if (!order.includes(d)) throw new Error("project not in src/projects/index.json: " + d);
for (const d of order) if (!dirs.includes(d)) throw new Error("index.json names a missing project: " + d);
const projects = order.map(id => {
  const files = {};
  const walkP = (dir, pre) => { for (const f of readdirSync(dir).sort()) { const full = join(dir, f); if (statSync(full).isDirectory()) walkP(full, pre + f + "/"); else files[pre + f] = readFileSync(full, "utf8"); } };
  walkP(P + id, "");
  JSON.parse(files["project.json"]);
  return { id, files };
});
writeFileSync(SITE + "app/content/projects.js", header("projects.js: the built-in projects, each a set of plain files (project.json, *.typed, scripts/*.js, ui/*.js, notes.md).").replace("edit the Markdown under src/ instead", "edit the files under src/projects/ instead") +
  "globalThis.WB_PROJECTS = " + JSON.stringify(projects) + ";\n");

const chapters = readdirSync(ROOT + "src/book").filter(f => f.endsWith(".md")).sort().map(f => {
  const text = readFileSync(ROOT + "src/book/" + f, "utf8");
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const meta = {};
  if (m) for (const line of m[1].split("\n")) { const [k, ...v] = line.split(":"); meta[k.trim()] = v.join(":").trim(); }
  const md = m ? text.slice(m[0].length) : text;
  return { id: meta.id, title: meta.title, part: meta.part || undefined, projects: (meta.projects || meta.presets) ? (meta.projects || meta.presets).split(",").map(s => s.trim()) : undefined, md };
});
for (const c of chapters) if (!c.id || !c.title) throw new Error("chapter without id or title: " + JSON.stringify(c).slice(0, 80));
for (const x of projects) { const ch = JSON.parse(x.files["project.json"]).chapter; if (ch && !chapters.some(c => c.id === ch)) throw new Error(`project ${x.id} names a missing chapter: ${ch}`); }
for (const c of chapters) for (const id of c.projects || []) if (!order.includes(id)) throw new Error(`chapter ${c.id} names a missing project: ${id}`);
for (const c of chapters) for (const m of c.md.matchAll(/\]\(project:([a-z0-9-]+)\)/g)) if (!order.includes(m[1])) throw new Error(`chapter ${c.id} links a missing project: ${m[1]}`);
for (const c of chapters) for (const m of c.md.matchAll(/\]\(chapter:([a-z0-9-]+)/g)) if (!chapters.some(x => x.id === m[1])) throw new Error(`chapter ${c.id} links a missing chapter: ${m[1]}`);
writeFileSync(SITE + "app/content/book.js", header("book.js: the book, Inside the Compiler Workbench, one entry per chapter.") +
  "globalThis.WB_BOOK = " + JSON.stringify(chapters) + ";\n");

const files = [];
const walk = dir => { for (const f of readdirSync(dir).sort()) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else files.push(relative(SITE, p)); } };
walk(SITE);
const skip = new Set(["app/sources.js", "app/content/book.js", "app/content/reference.js", "app/content/references.js", "app/content/projects.js", "app/content/presets.js"]);
const sources = {};
for (const f of files) if (!skip.has(f) && /\.(js|css|html)$/.test(f)) sources[f] = readFileSync(SITE + f, "utf8");
sources["src/reference.md"] = readFileSync(ROOT + "src/reference.md", "utf8");
for (const f of readdirSync(ROOT + "src/book").sort()) sources["src/book/" + f] = readFileSync(ROOT + "src/book/" + f, "utf8");
for (const f of ["test/projects.mjs", "test/build.mjs", "test/load.mjs"]) sources[f] = readFileSync(ROOT + f, "utf8");
writeFileSync(SITE + "app/sources.js", "// sources.js: every file of the workbench, embedded so wb.source can read the code that is running. Generated by test/build.mjs.\nglobalThis.WB_SOURCES = " + JSON.stringify(sources) + ";\n");
const size = Object.values(sources).reduce((n, s) => n + s.length, 0);
console.log(`${projects.length} projects · reference ${readFileSync(ROOT + "src/reference.md", "utf8").length} chars · ${chapters.length} chapters · ${Object.keys(sources).length} source files, ${(size / 1024).toFixed(0)} KB`);
