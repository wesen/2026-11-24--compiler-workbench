// Verify the identities table (src/typed/rules/identities.ts) with the options the simplify and fold records use
// (1e6 random assignments, seed 7, exhaustive over 2^32 where a rule has one full variable and no proof), and write
// src/typed/rules/evidence-identities.ts. As IRWB-006 scripts/04-verify-rules.mjs, for this table.
//   node 17-identities-evidence.mjs [--no-exhaustive]
import { writeFileSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
const here = new URL('../../../../../../', import.meta.url);
const ROOT = process.env.IRWB_ROOT ? pathToFileURL(process.env.IRWB_ROOT + '/').href : here.href;
const { verifyRule } = await import(ROOT + 'dist/typed/rules/verify.js');
const { IDENTITY_RULES } = await import(ROOT + 'dist/typed/rules/identities.js');
const opts = { random: 1e6, seed: 7, exhaustive32: !process.argv.includes('--no-exhaustive') };
const table = {};
const t0 = performance.now();
for (const r of IDENTITY_RULES.rules) {
  const t = performance.now();
  const e = verifyRule(r, opts);
  table[r.name] = e;
  console.log(`${r.name.padEnd(16)} ${e.verdict.padEnd(8)} ${(e.strength ?? '-').padEnd(12)} ${String(Math.round(performance.now() - t)).padStart(8)} ms  ${e.methods.filter(m => m.verdict !== 'n/a').map(m => m.method).join(',')}`);
}
const ms = Math.round(performance.now() - t0);
writeFileSync(
  fileURLToPath(new URL('src/typed/rules/evidence-identities.ts', here)),
  `/**
 * Recorded verification evidence for the identities table (IRWB-037-G), keyed by rule name. Generated by
 * ttmp/2026/11/27/IRWB-037-G--…/scripts/17-identities-evidence.mjs with ${JSON.stringify(opts)} in ${ms} ms; do not edit by
 * hand. A test fails when a rule no longer matches its record's fingerprint.
 */
import type { RuleEvidence } from './verify.js';

export const IDENTITY_EVIDENCE_OPTIONS = ${JSON.stringify(opts)} as const;
export const IDENTITY_EVIDENCE: Readonly<Record<string, RuleEvidence>> = ${JSON.stringify(table, null, 2)};
`,
);
console.log(JSON.stringify({ rules: Object.keys(table).length, ms }));
