// IRWB-029-D: which statements of a Tix function can share a CUDA kernel without changing any result bit, decided
// from the Tix IR alone, before code generation (design-doc/01 in the ticket).
//
// A group is a contiguous run of statements whose first `depth` axes have equal extents (the block domain). A
// statement joins the current group when it reads a member, and every read of a member has, in each of the first
// `depth` positions, exactly the reader's own axis there. Each block-domain point then needs only its own slice of
// every member, so the group can compute its members in order, point by point:
//   - thread mode (every member has rank `depth`): one thread per point; a member is a register;
//   - block mode (some member has trailing axes): one block per point; a member's row lives in a row buffer, a
//     member with no trailing axes is computed by thread 0, and `__syncthreads()` separates the members.
// Every element is still computed by one thread with stage 2's scalar code, so its evaluation order is unchanged.
//
// IRWB-030-F adds two decisions on top of the legality plan:
//   - `parallelTerms`: the outermost reductions of a block-mode row-scalar member whose terms are computed by all
//     the block's threads into a shared term buffer and folded in order by thread 0 (still bit-identical: each
//     term is computed by the same scalar code, and the fold keeps the meaning's accumulation order). Refused
//     bodies are recorded in the group's reasons.
//   - `gatedPlan(fn, shapeValues)`: a cost gate that replaces a block-mode group with stage 2's per-statement
//     kernels when its fused parallelism (points x threads per block) would leave the GPU unsaturated while the
//     unfused mapping (points x row length) would not. `planFusion` alone stays pure and fully fused: it is what
//     `cudaSource` emits and `checkLowering` checks; `runTixCuda` knows the launch shapes and uses the gate.
import { plain, value, visit, width, type Affine, type Axis, type Expr, type Fn, type Statement, type Tensor } from './model.js';

export interface FusionGroup {
  kernel: string;
  /** Member statements, in source order. */
  statements: string[];
  /** Number of leading axes shared by the members (the block domain). */
  depth: number;
  mapping: 'thread' | 'block';
  /** Members written to global memory: the result, those read by a later kernel, and every singleton. */
  stored: string[];
  /** Block mode: members read by a later member, kept in a row buffer. */
  buffered: string[];
  /** Block mode: other tensors whose block-domain rows are copied to a row buffer before the members run. */
  staged: string[];
  /** Block mode: outermost reductions of row-scalar members computed as parallel terms and a serial in-order
   * fold (IRWB-030-F). The path navigates child indices from the member's expression to the reduce node. */
  parallelTerms: ParallelTerm[];
  /** Why the statements share this kernel, and what changed in the thread mapping. */
  reasons: string[];
}
export interface ParallelTerm {
  /** The row-scalar member whose reduction is staged. */
  statement: string;
  /** Child indices from the member's expression to the outermost reduce node. */
  path: number[];
  /** Human-readable description, e.g. `mean: sum(D)`. */
  description: string;
}
export interface FusionRefusal {
  statement: string;
  kernel: string;
  reason: string;
}
export interface FusionPlan {
  fn: string;
  groups: FusionGroup[];
  refusals: FusionRefusal[];
}

type Load = Extract<Expr, { kind: 'load' }>;
const same = (a: Affine, b: Affine) => JSON.stringify(a) === JSON.stringify(b);
function loads(s: Statement): Load[] {
  const out: Load[] = [];
  visit(s.expr, e => {
    if (e.kind === 'load') out.push(e);
  });
  return out;
}
const text = (a: Affine) =>
  [
    ...a.terms.map(([n, k]) => (k === 1 ? n : `${k}*${n}`)),
    ...(a.constant || !a.terms.length ? [a.constant] : []),
  ].join(' + ');
const extentText = (a: Axis) => {
  const e = a.extent;
  if (e.kind === 'tail') return `tail(${text(e.dim)})`;
  return e.kind === 'dim' ? text(e.dim) : `${e.rounding === 'ceil' ? 'ceil' : 'floor'}(${text(e.dim)} / ${width})`;
};

/** The outermost reductions of a row-scalar member whose terms can be computed in parallel, with the refusals.
 * A reduction's body cannot mention the accumulator, so every term is a pure function of loads and any thread can
 * compute it; one thread folds the computed terms in the meaning's order. Refused (IRWB-030-F design):
 *   - a bare-load body: the serial chain is the fold itself (loads pipeline behind the dependent adds), so staging
 *     only adds a shared round trip and a barrier per term;
 *   - a `tail` axis: the flat term index could not be decomposed in lexicographic order (never generated by the
 *     checked passes; split-sum nests the tail inside the block reduction, which stays serial within its term);
 *   - nested reductions: they are part of their term's value; staging the leaves would reassociate a split sum.
 * Row members (rank > depth) are refused wholesale: their elements are already computed by different threads of
 * the block, and staging their terms would need the whole row's terms in memory. */
function stageableReductions(m: Statement): { staged: ParallelTerm[]; reasons: string[] } {
  const staged: ParallelTerm[] = [],
    reasons: string[] = [];
  const walk = (e: Expr, path: number[]) => {
    if (e.kind === 'reduce') {
      const bareLoad = e.body.kind === 'load';
      const tail = e.axes.find(a => a.extent.kind === 'tail');
      const axes = e.axes.map(a => extentText(a)).join(',');
      if (tail) {
        reasons.push(
          `${e.op}(${axes}) of ${m.name} keeps the serial fold: a tail axis cannot be enumerated by a flat term index`,
        );
      } else if (bareLoad) {
        reasons.push(
          `${e.op}(${axes}) of ${m.name} keeps the serial fold: its body is a bare load, so the fold's own chain dominates and staging only adds a shared round trip`,
        );
      } else {
        staged.push({ statement: m.name, path, description: `${m.name}: ${e.op}(${axes})` });
        if (e.body.kind !== 'load' && hasReduce(e.body))
          reasons.push(
            `the nested reduction inside ${e.op}(${axes}) of ${m.name} folds serially within its term, keeping the split sum's order`,
          );
      }
      return;
    }
    if (e.kind === 'op') e.args.forEach((a, i) => walk(a, [...path, i]));
  };
  walk(m.expr, []);
  return { staged, reasons };
}
function hasReduce(e: Expr): boolean {
  if (e.kind === 'reduce') return true;
  if (e.kind === 'op') return e.args.some(hasReduce);
  return false;
}

/** The deepest block domain s can share with the group's members, or 0 with the reason it cannot join. */
function joinDepth(s: Statement, members: Statement[], depth: number): { depth: number; reason: string } {
  const names = new Set(members.map(m => m.name));
  const reads = loads(s).filter(e => names.has(e.name));
  if (!reads.length) return { depth: 0, reason: 'reads no tensor of the kernel (no horizontal fusion)' };
  let k = Math.min(depth, s.axes.length),
    reason = `it has ${s.axes.length} ${s.axes.length === 1 ? 'axis' : 'axes'}`;
  for (let p = 0; p < k; p++)
    if (!same(s.shape[p], members[0].shape[p])) {
      [k, reason] = [
        p,
        `its axis ${p} has extent ${text(s.shape[p])}, the kernel's ${text(members[0].shape[p])}`,
      ];
      break;
    }
  for (const r of reads)
    for (let p = 0; p < k; p++)
      if (plain(r.indices[p]) !== s.axes[p].id) {
        const at = text(r.indices[p]);
        [k, reason] = [p, `reads ${r.name} at index ${at} in position ${p}, not its own axis there`];
        break;
      }
  return { depth: k, reason };
}

export function planFusion(fn: Fn): FusionPlan {
  const runs: { members: Statement[]; depth: number; reasons: string[] }[] = [];
  const refusals: FusionRefusal[] = [];
  for (const s of fn.statements) {
    const current = runs.at(-1);
    if (current) {
      const join = joinDepth(s, current.members, current.depth);
      if (join.depth > 0) {
        if (join.depth < current.depth)
          current.reasons.push(
            `${s.name} narrows the block domain to ${join.depth} ${join.depth === 1 ? 'axis' : 'axes'}: ${join.reason}`,
          );
        current.members.push(s);
        current.depth = join.depth;
        continue;
      }
      refusals.push({ statement: s.name, kernel: 'k' + (runs.length - 1), reason: join.reason });
    }
    runs.push({ members: [s], depth: s.axes.length, reasons: [] });
  }
  const readers = new Map<string, number[]>();
  runs.forEach((run, g) =>
    run.members.forEach(s => loads(s).forEach(e => readers.set(e.name, [...(readers.get(e.name) ?? []), g]))),
  );
  const groups = runs.map(({ members, depth, reasons }, g): FusionGroup => {
    const names = new Set(members.map(m => m.name));
    const single = members.length === 1;
    const stored = members
      .filter(m => single || m.name === fn.result || (readers.get(m.name) ?? []).some(r => r > g))
      .map(m => m.name);
    const block = members.some(m => m.axes.length > depth);
    const buffered = block
      ? members.filter((m, i) => members.slice(i + 1).some(r => loads(r).some(e => e.name === m.name)))
      : [];
    const staged = new Set<string>();
    const tensors = new Map([...fn.params, ...fn.statements].map(t => [t.name, t]));
    if (block)
      for (const m of members)
        for (const e of loads(m)) {
          const t = tensors.get(e.name)!;
          if (names.has(e.name) || t.shape.length <= depth) continue;
          const rows = members[0].shape.slice(0, depth);
          if (rows.every((d, p) => same(d, t.shape[p]) && plain(e.indices[p]) === m.axes[p].id))
            staged.add(e.name);
        }
    // IRWB-030-F: stage the terms of a row-scalar member's outermost reductions.
    const parallelTerms: ParallelTerm[] = [];
    if (block)
      for (const m of members)
        if (m.axes.length === depth) {
          const { staged: terms, reasons: why } = stageableReductions(m);
          parallelTerms.push(...terms);
          reasons.push(...why);
        }
    if (block)
      for (const m of members)
        if (m.axes.length > depth && hasReduce(m.expr))
          reasons.push(
            `the reductions inside ${m.name} stay serial per element: the row's threads already compute its elements concurrently, and staging them would need the whole row's terms in memory`,
          );
    const axes = members[0].shape.slice(0, depth).map(text).join(', ');
    const why = single
      ? []
      : block
        ? [
            `one block per point of [${axes}] instead of one thread per element; the members run in order, ` +
              'separated by barriers, each element by one thread',
            ...members
              .filter(m => m.axes.length === depth)
              .map(m => `thread 0 computes ${m.name} (one element per row) in the meaning's order`),
            ...(staged.size ? [`rows of ${[...staged].join(', ')} are staged in the row buffer`] : []),
            ...(parallelTerms.length
              ? [
                  `the terms of ${parallelTerms.map(t => t.description).join(', ')} are computed in parallel by the block and folded in order by thread 0`,
                ]
              : []),
          ]
        : [
            `one thread per element of [${axes}] computes ${members.map(m => m.name).join(', ')} in registers`,
          ];
    return {
      kernel: 'k' + g,
      statements: members.map(m => m.name),
      depth,
      mapping: block ? 'block' : 'thread',
      stored,
      buffered: buffered.map(m => m.name),
      staged: [...staged],
      parallelTerms,
      reasons: [...why, ...reasons],
    };
  });
  return { fn: fn.name, groups, refusals };
}

// Threads per block in block mode (IRWB-029-D diary step 4, caps 64, 128 and 256 measured on softmax, layernorm,
// attention and mlp): 64 when a member's reduction reads a tensor from global memory (a contraction operand:
// attention's k and v, mlp's w and v), 128 otherwise (rows only: softmax, layernorm).
export const blockThreads = { rows: 128, contraction: 64 };

/** A group's block-mode thread cap: 64 when some member's reduction reads a tensor from global memory. */
export function groupCap(group: FusionGroup, tensors: ReadonlyMap<string, Tensor>): number {
  const rowBuffers = [...group.staged, ...group.buffered];
  const operands = (e: Expr, inReduction: boolean): boolean =>
    e.kind === 'load'
      ? inReduction && !rowBuffers.includes(e.name)
      : e.kind === 'op'
        ? e.args.some(a => operands(a, inReduction))
        : e.kind === 'reduce' && operands(e.body, true);
  const members = group.statements.map(n => tensors.get(n) as Statement);
  return members.some(m => operands(m.expr, false)) ? blockThreads.contraction : blockThreads.rows;
}

// IRWB-030-F cost gate. In block mode the row members run on `points x threads-per-block` threads, each
// computing `row-length / threads` elements, where stage 2 runs `points x row-length` threads, one element each.
// When `points x threads` already saturates the GPU, the total work decides and fusion also saves global
// traffic; when it does not and the unfused mapping would saturate, fusion is slower. The constant below is the
// upper edge of the measured crossover band, not a round number: scripts 02 and 03 in the ticket sweep fused
// against unfused over the number of rows. The one family that crosses is mlp (every row member a contraction
// reading a strided global operand): fused/unfused is 1.78 at 8 192 fused threads, 1.19 at 12 288 and 0.99 at
// 16 384, so the gate refuses below 16 384. The streaming families (softmax, layernorm) and attention never
// crossed: down to 512 fused threads they are faster fused (0.45x to 0.9x), because their row-scalar members
// carry a reduction that spans the row, and stage 2 pays the same serial fold on one thread per row - so the
// second clause fuses those groups at any size.
export const gateThreads = 16384;

/** The serial term count of an expression at the given shape values: a reduction contributes the product of its
 * axes' extents times its body's terms per iteration (a split sum's outer fold is short, but each of its terms
 * carries the inner sum, so the count stays proportional to the row it spans). Loads and literals are one step. */
function serialTerms(e: Expr, dims: ReadonlyMap<string, number>): number | undefined {
  switch (e.kind) {
    case 'reduce': {
      let outer = 1;
      for (const a of e.axes) {
        const x = a.extent;
        if (x.kind === 'tail') return undefined;
        const dim = value(x.dim, dims);
        if (!Number.isSafeInteger(dim) || dim < 0) return undefined;
        outer *= x.kind === 'dim' ? dim : Math[x.rounding](dim / width);
      }
      const body = serialTerms(e.body, dims);
      return body === undefined ? undefined : outer * (1 + body);
    }
    case 'op': {
      let sum = 0;
      for (const a of e.args) {
        const n = serialTerms(a, dims);
        if (n === undefined) return undefined;
        sum += n;
      }
      return sum;
    }
    default:
      return 1;
  }
}

/** The gate's decision for one block-mode group at the given shape values: fuse, or fall back to stage 2. */
function gateFuses(
  group: FusionGroup,
  tensors: ReadonlyMap<string, Tensor>,
  dims: ReadonlyMap<string, number>,
): { fuse: boolean; points: number; threads: number; longest: number; serial: number } | undefined {
  const dim = (a: Affine) => {
    const n = value(a, dims);
    return Number.isSafeInteger(n) && n >= 0 ? n : undefined;
  };
  const domain = (tensors.get(group.statements[0]) as Statement).shape.slice(0, group.depth);
  let points = 1;
  for (let p = 0; p < group.depth; p++) {
    const n = dim(domain[p]);
    if (n === undefined) return undefined;
    points *= n;
  }
  let longest = 1;
  for (const name of [...group.staged, ...group.statements]) {
    let product = 1;
    for (const a of tensors.get(name)!.shape.slice(group.depth)) {
      const n = dim(a);
      if (n === undefined) return undefined;
      product *= n;
    }
    longest = Math.max(longest, product);
  }
  const threads = Math.min(groupCap(group, tensors), Math.max(32, Math.ceil(longest / 32) * 32));
  // The serial chain a row-scalar member's reduction puts on one thread, at its deepest the longest row.
  let serial = 0;
  for (const name of group.statements) {
    const m = tensors.get(name) as Statement;
    if (m.axes.length !== group.depth) continue;
    const terms = serialTerms(m.expr, dims);
    if (terms === undefined) return undefined;
    serial = Math.max(serial, terms);
  }
  // A row that fits in its block's threads keeps stage 2's concurrency; a longer row loses it, so the group
  // fuses only when the fused thread count still reaches the measured saturation threshold - unless a
  // row-scalar reduction spans the row, in which case stage 2 pays the same serial fold on fewer threads and
  // the fused kernel was measured never slower at any size.
  const fuse =
    longest <= threads || points * threads >= gateThreads || serial >= longest;
  return { fuse, points, threads, longest, serial };
}

/** Stage 3's plan with the cost gate applied at the launch shape values (IRWB-030-F). A block-mode group whose
 * fused parallelism would leave the GPU unsaturated is replaced by stage 2's per-statement kernels, with the
 * numbers recorded as a refusal. Without shape values the plan is unchanged. */
export function gatedPlan(fn: Fn, dims?: ReadonlyMap<string, number>): FusionPlan {
  const plan = planFusion(fn);
  if (!dims || !plan.groups.some(g => g.mapping === 'block')) return plan;
  const tensors = new Map<string, Tensor>([...fn.params, ...fn.statements].map(t => [t.name, t]));
  const refusals = [...plan.refusals];
  const groups: FusionGroup[] = [];
  for (const g of plan.groups) {
    if (g.mapping !== 'block') {
      groups.push(g);
      continue;
    }
    const decision = gateFuses(g, tensors, dims);
    if (!decision || decision.fuse) {
      groups.push(g);
      continue;
    }
    refusals.push({
      statement: g.statements.join(', '),
      kernel: 'k' + groups.length,
      reason:
        `${decision.points} block points x ${decision.threads} threads = ${decision.points * decision.threads}` +
        ` fused threads, below the measured ${gateThreads} that saturate the GPU, with rows of ${decision.longest}` +
        ' elements and no row reduction spanning a row to equalize the serial cost: the row members would run' +
        ' on fewer threads than stage 2, so the group stays unfused',
    });
    for (const s of g.statements) {
      const single = tensors.get(s) as Statement;
      groups.push({
        kernel: 'k' + groups.length,
        statements: [s],
        depth: single.axes.length,
        mapping: 'thread',
        stored: [s],
        buffered: [],
        staged: [],
        parallelTerms: [],
        reasons: [],
      });
    }
  }
  return { fn: fn.name, groups, refusals };
}

/** Stage 2's plan: one thread-mode kernel per statement. */
export function unfusedPlan(fn: Fn): FusionPlan {
  return {
    fn: fn.name,
    groups: fn.statements.map((s, g) => ({
      kernel: 'k' + g,
      statements: [s.name],
      depth: s.axes.length,
      mapping: 'thread',
      stored: [s.name],
      buffered: [],
      staged: [],
      parallelTerms: [],
      reasons: [],
    })),
    refusals: [],
  };
}
